package com.example.util

import android.content.Context
import android.content.Intent
import android.util.Log
import com.example.BuildConfig
import com.google.firebase.FirebaseApp
import com.google.firebase.appcheck.FirebaseAppCheck
import com.google.firebase.appcheck.debug.DebugAppCheckProviderFactory
import com.google.firebase.appcheck.recaptcha.RecaptchaAppCheckProviderFactory

private const val TAG = "AppCheckInit"

private const val DEBUG_TOKEN_EXTRA = "FIREBASE_APPCHECK_DEBUG_TOKEN"
private const val DEBUG_STORE_PREFIX = "com.google.firebase.appcheck.debug.store."
private const val DEBUG_SECRET_KEY = "com.google.firebase.appcheck.debug.DEBUG_SECRET"
private const val EXPLICIT_DEBUG_PREFS = "sat_appcheck_prefs"
private const val KEY_HAS_EXPLICIT_DEBUG_TOKEN = "has_explicit_debug_token"
private const val RECAPTCHA_SITE_KEY_RES = "recaptcha_site_key"

internal enum class AppCheckProviderChoice {
    DEBUG,
    RECAPTCHA
}

internal fun resolveAppCheckProviderChoice(
    isDebugBuild: Boolean,
    intentDebugToken: String?,
    hasExplicitStoredDebugToken: Boolean,
    recaptchaSiteKey: String?
): AppCheckProviderChoice {
    if (isDebugBuild) {
        if (!intentDebugToken.isNullOrBlank() || hasExplicitStoredDebugToken) {
            return AppCheckProviderChoice.DEBUG
        }
        if (!recaptchaSiteKey.isNullOrBlank()) {
            return AppCheckProviderChoice.RECAPTCHA
        }
        return AppCheckProviderChoice.DEBUG
    }
    return AppCheckProviderChoice.RECAPTCHA
}

fun configureAppCheck(context: Context, intent: Intent?) {
    try {
        if (FirebaseApp.getApps(context).isEmpty()) {
            FirebaseApp.initializeApp(context)
        }

        val persistenceKey = FirebaseApp.getInstance().persistenceKey
        val debugStorePrefs = context.getSharedPreferences(
            "$DEBUG_STORE_PREFIX$persistenceKey",
            Context.MODE_PRIVATE
        )
        val explicitPrefs = context.getSharedPreferences(EXPLICIT_DEBUG_PREFS, Context.MODE_PRIVATE)
        val intentDebugToken = intent?.getStringExtra(DEBUG_TOKEN_EXTRA)?.trim()

        if (BuildConfig.DEBUG && !intentDebugToken.isNullOrEmpty()) {
            // Synchronous commit() is required before DebugAppCheckProviderFactory initializes.
            debugStorePrefs.edit()
                .putString(DEBUG_SECRET_KEY, intentDebugToken)
                .commit()
            explicitPrefs.edit()
                .putBoolean(KEY_HAS_EXPLICIT_DEBUG_TOKEN, true)
                .commit()
            Log.d(TAG, "App Check debug secret configured from launch Intent.")
        }

        val hasExplicitStoredDebugToken = explicitPrefs.getBoolean(KEY_HAS_EXPLICIT_DEBUG_TOKEN, false) &&
            !debugStorePrefs.getString(DEBUG_SECRET_KEY, null).isNullOrBlank()

        val recaptchaSiteKey = resolveRecaptchaSiteKey(context)
        val choice = resolveAppCheckProviderChoice(
            isDebugBuild = BuildConfig.DEBUG,
            intentDebugToken = intentDebugToken,
            hasExplicitStoredDebugToken = hasExplicitStoredDebugToken,
            recaptchaSiteKey = recaptchaSiteKey
        )

        when (choice) {
            AppCheckProviderChoice.DEBUG -> {
                if (intentDebugToken.isNullOrEmpty() && !hasExplicitStoredDebugToken) {
                    Log.w(TAG, "No explicit debug token or reCAPTCHA key; installing DebugAppCheckProviderFactory.")
                }
                FirebaseAppCheck.getInstance().installAppCheckProviderFactory(
                    DebugAppCheckProviderFactory.getInstance()
                )
                Log.d(TAG, "DebugAppCheckProviderFactory installed.")
            }

            AppCheckProviderChoice.RECAPTCHA -> {
                if (BuildConfig.DEBUG && !hasExplicitStoredDebugToken) {
                    // Remove any unregistered random debug secret generated by earlier debug launches.
                    if (debugStorePrefs.contains(DEBUG_SECRET_KEY)) {
                        debugStorePrefs.edit().remove(DEBUG_SECRET_KEY).commit()
                    }
                    Log.d(
                        TAG,
                        "No launch debug token present on external device; using RecaptchaAppCheckProviderFactory."
                    )
                }
                if (!recaptchaSiteKey.isNullOrBlank()) {
                    FirebaseAppCheck.getInstance().installAppCheckProviderFactory(
                        RecaptchaAppCheckProviderFactory.getInstance(recaptchaSiteKey)
                    )
                    Log.d(TAG, "RecaptchaAppCheckProviderFactory installed.")
                } else {
                    Log.e(TAG, "recaptcha_site_key resource is missing or blank.")
                }
            }
        }
    } catch (e: Exception) {
        Log.e(TAG, "Failed to initialize Firebase App Check", e)
    }
}

private fun resolveRecaptchaSiteKey(context: Context): String? {
    val resId = context.resources.getIdentifier(
        RECAPTCHA_SITE_KEY_RES,
        "string",
        context.packageName
    )
    if (resId == 0) return null
    return context.getString(resId).trim().takeIf { it.isNotBlank() }
}
